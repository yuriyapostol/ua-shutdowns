// Run with popup.html and in-memory storage/clipboard fixtures.
async () => {
  if (!window.previewData || !window.copiedSchedules) throw new Error('In-memory date fixtures required');
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const wait = async read => {
    for (let i = 0; i < 100; i++) { if (read()) return; await new Promise(resolve => setTimeout(resolve, 10)); }
    throw new Error('Date operation did not finish');
  };
  const byId = id => document.getElementById(id);
  const date = byId('schedule-date');
  const picker = byId('date-picker-toggle');
  const readDate = () => date.value.split('.').reverse().join('-');
  const today = DtekSchedule.dateKey();
  const yesterday = DtekSchedule.shiftDate(today, -1);
  const tomorrow = DtekSchedule.shiftDate(today, 1);
  const choose = value => {
    if (byId('date-calendar').hidden) picker.click();
    const [year, month] = value.split('-').map(Number);
    byId('calendar-year').value = year;
    byId('calendar-year').dispatchEvent(new Event('change', { bubbles: true }));
    byId('calendar-month').value = month;
    byId('calendar-month').dispatchEvent(new Event('change', { bubbles: true }));
    document.querySelector(`[data-date="${value}"]`).click();
  };
  const typeDate = value => {
    date.value = value;
    date.dispatchEvent(new Event('input', { bubbles: true }));
    date.dispatchEvent(new Event('change', { bubbles: true }));
  };
  const selectedShortcut = () => [...document.querySelectorAll('.date-shortcut[aria-pressed="true"]')].map(item => item.id).join(',');
  const address = (await AddressSettings.list()).find(item => item.id === 'fixture-1');
  const card = () => [...document.querySelectorAll('.address-card')].find(item =>
    item.querySelector('strong').textContent === `${address.street}, ${address.house}`);
  assert(date.type === 'text' && readDate() === today, 'The calendar must start on today');
  assert(selectedShortcut() === 'date-today', 'Today shortcut must start selected');
  assert([...document.querySelectorAll('.date-shortcut')].every(item => item.getBoundingClientRect().height <= 26), 'Date shortcuts must remain compact');
  byId('date-tomorrow').click();
  assert(readDate() === tomorrow && selectedShortcut() === 'date-tomorrow', 'Tomorrow shortcut must select tomorrow');
  byId('date-today').click();
  assert(readDate() === today && selectedShortcut() === 'date-today', 'Today shortcut must return to today');
  typeDate('29.02.2024');
  assert(readDate() === '2024-02-29' && selectedShortcut() === 'date-other', 'Typing must select a valid date');
  typeDate('31.02.2024');
  assert(date.getAttribute('aria-invalid') === 'true' && selectedShortcut() === 'date-other', 'Impossible dates must preserve the selected day and show an error');
  date.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert(readDate() === '2024-02-29' && !date.hasAttribute('aria-invalid'), 'Escape must restore the selected date');
  typeDate('1.3.2024');
  assert(date.value === '01.03.2024', 'Short dates must be normalized');
  byId('date-today').click();
  date.focus();
  assert(!byId('date-calendar').hidden && document.activeElement === date, 'Focusing the date input must open the calendar and preserve text editing');
  assert(picker.querySelector('img').getAttribute('src') === 'images/calendar.svg' &&
    getComputedStyle(picker.querySelector('img')).transform === 'none', 'The calendar icon must stay upright while open');
  const settleSelection = () => new Promise(resolve => setTimeout(resolve, 20));
  const assertSelection = (start, end, message) => assert(date.selectionStart === start && date.selectionEnd === end, message);
  date.blur();
  date.setSelectionRange(date.value.length, date.value.length);
  date.focus();
  assertSelection(0, 2, 'Focus without a pointer position must select the day even when the old caret was at the end');
  for (const [position, start, end] of [[1, 1, 1], [4, 3, 5], [3, 3, 3], [8, 6, 10], [7, 7, 7]]) {
    date.setSelectionRange(position, position);
    await settleSelection();
    assertSelection(start, end, 'Only entering another component must select it');
  }
  date.setSelectionRange(1, 8);
  await settleSelection();
  assertSelection(1, 8, 'Manual text selections must be preserved');
  date.blur();
  date.setSelectionRange(0, 0);
  date.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }));
  date.focus();
  date.setSelectionRange(4, 4);
  document.dispatchEvent(new PointerEvent('pointerup', { bubbles: true }));
  await settleSelection();
  assertSelection(3, 5, 'Pointer focus must select the clicked component');
  date.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }));
  date.setSelectionRange(4, 4);
  document.dispatchEvent(new PointerEvent('pointerup', { bubbles: true }));
  await settleSelection();
  assertSelection(4, 4, 'Clicking inside the same component must preserve the caret');
  const typedValue = date.value;
  date.setRangeText('1', 3, 5, 'end');
  date.dispatchEvent(new Event('input', { bubbles: true }));
  await settleSelection();
  assertSelection(4, 4, 'Typing must preserve the resulting caret');
  date.value = typedValue;
  date.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert(byId('date-calendar').hidden && document.activeElement === date, 'Escape must close the calendar without reopening on restored focus');
  date.setSelectionRange(6, 10);
  picker.focus();
  picker.click();
  assert(!byId('date-calendar').hidden && document.activeElement === date, 'Opening with the calendar icon must focus the date input');
  assertSelection(0, 2, 'Opening with the calendar icon must select the day');
  date.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true }));
  assert(document.activeElement === byId('calendar-previous') && !byId('date-calendar').hidden, 'Tab from the date input must enter the calendar');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, bubbles: true, cancelable: true }));
  assert(document.activeElement === picker, 'Shift+Tab from the first calendar control must return to its icon');
  picker.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true }));
  assert(document.activeElement === byId('calendar-previous'), 'Tab from the calendar icon must enter the calendar');
  document.querySelector('.calendar-day[tabindex="0"]').focus();
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true }));
  assert(document.activeElement === byId('date-next') && byId('date-calendar').hidden, 'Tab after the calendar must reach the next-day button and close the calendar');
  picker.click();
  date.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  byId('schedule-date-control').click();
  assert(!byId('date-calendar').hidden && document.activeElement === date, 'Clicking the date control must open the calendar');
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  const listTop = byId('address-list').getBoundingClientRect().top;
  byId('date-other').click();
  assert(byId('address-list').getBoundingClientRect().top === listTop, 'Opening the calendar must not move the schedule');
  assert(getComputedStyle(byId('date-calendar')).boxShadow !== 'none', 'The calendar dropdown must have a shadow');
  const calendarBounds = byId('date-calendar').getBoundingClientRect();
  assert(calendarBounds.top >= 0 && calendarBounds.bottom <= document.documentElement.clientHeight, 'The calendar must fit inside the popup viewport');
  assert(calendarBounds.left >= 0 && calendarBounds.right <= document.documentElement.clientWidth, 'The calendar must fit the popup width');
  assert(!byId('date-calendar').hidden && readDate() === today && selectedShortcut() === 'date-today', 'Other date must open the calendar without changing the date');
  assert(document.activeElement.dataset.date === today, 'Opening the calendar must focus the selected day');
  const todayStyle = getComputedStyle(document.querySelector('.calendar-day[aria-current="date"]'));
  assert(todayStyle.borderColor === 'rgb(137, 144, 150)' && todayStyle.backgroundColor === 'rgb(255, 227, 0)', 'Selected today must retain its outline on the yellow background');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert(document.activeElement.dataset.date === tomorrow && readDate() === today, 'Arrow keys must move focus without selecting');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert(byId('date-calendar').hidden && document.activeElement === byId('date-other'), 'Escape must close the calendar and restore focus');
  choose('2024-02-29');
  assert(readDate() === '2024-02-29' && byId('date-calendar').hidden, 'Leap day must be selectable and close the calendar');
  picker.click();
  byId('calendar-year-next').click();
  assert(byId('calendar-year').value === '2025' && !document.querySelector('[data-date="2025-02-29"]'), 'Year arrows must handle leap years');
  byId('calendar-year-previous').click();
  assert(byId('calendar-year').value === '2024' && byId('calendar-month').value === '2', 'Year arrows must preserve the month');
  byId('calendar-next').click();
  assert(byId('calendar-month').value === '3' && readDate() === '2024-02-29', 'Browsing months must preserve selection');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  choose('0001-01-01');
  picker.click();
  assert(byId('calendar-previous').disabled && byId('calendar-year-previous').disabled, 'First supported month must disable previous');
  date.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true }));
  assert(document.activeElement === byId('calendar-month'), 'Tab into the calendar must skip disabled controls');
  document.querySelector('[data-date="0001-01-01"]').focus();
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
  assert(document.activeElement.dataset.date === '0001-01-01', 'Keyboard navigation must respect the lower boundary');
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  choose('9999-12-31');
  picker.click();
  assert(byId('calendar-next').disabled && byId('calendar-year-next').disabled, 'Last supported month must disable next');
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  byId('date-today').click();
  byId('date-previous').click();
  assert(readDate() === yesterday, 'Previous must select yesterday');
  assert(selectedShortcut() === 'date-other', 'Previous day must select the other-date shortcut');
  assert(card().querySelector('.outage-interval').textContent === '01:00 – 02:00', 'Yesterday must show its archived intervals');
  assert(card().querySelector('.address-queue').textContent === 'Черга 4.2', 'Yesterday must show its historical queue');
  const count = copiedSchedules.length;
  card().querySelector('.share-schedule').click();
  assert(!byId('share-view').hidden, 'Sharing must open for the selected historical day');
  byId('copy-shared-schedule').click();
  await wait(() => copiedSchedules.length === count + 1);
  assert(copiedSchedules[count] === DtekSchedule.toText(address, DtekSites.get(address.region), address.schedules[yesterday]), 'Historical copy must use the selected day');
  byId('nav-back').click();
  assert(readDate() === yesterday, 'Returning from sharing must preserve the selected date');
  byId('date-next').click();
  assert(readDate() === today, 'Next must return to today');
  assert(selectedShortcut() === 'date-today', 'Arrow navigation must synchronize the today shortcut');
  choose(tomorrow);
  assert(readDate() === tomorrow && card().querySelector('.outage-note').textContent === 'Без відключень', 'The calendar must select tomorrow');
  assert(selectedShortcut() === 'date-tomorrow', 'Calendar selection must synchronize the tomorrow shortcut');
  choose(DtekSchedule.shiftDate(today, -10));
  assert(card().querySelector('.outage-note').textContent === 'Графік не збережено', 'Unknown historical data must not show another day');
  assert(card().querySelector('.share-schedule').disabled, 'Missing historical data cannot be shared');
  assert(selectedShortcut() === 'date-other', 'A calendar date outside today/tomorrow must select other');
  choose(yesterday);
  const original = structuredClone(address.schedules[yesterday]);
  await AddressSettings.saveQueue(address, '6.1', { date: today, lines: [[[180, 240]]] });
  await wait(() => card().querySelector('.outage-interval').textContent === '01:00 – 02:00');
  assert(readDate() === yesterday && card().querySelector('.outage-interval').textContent === '01:00 – 02:00', 'A live update must keep the selected historical day');
  assert(JSON.stringify((await AddressSettings.list()).find(item => item.id === address.id).schedules[yesterday]) === JSON.stringify(original), 'Today updates must preserve yesterday');
  choose(today);
  await wait(() => card().querySelector('.outage-interval').textContent === '03:00 – 04:00');
  assert(card().querySelector('.address-queue').textContent === 'Черга 6.1', 'Today must show its new queue');
  picker.click();
  byId('calendar-year').value = '';
  byId('calendar-year').dispatchEvent(new Event('change', { bubbles: true }));
  assert(readDate() === today && byId('calendar-year').value === String(Number(today.slice(0, 4))), 'An invalid year must preserve selection and restore the year');
  byId('open-settings').click();
  assert(byId('date-calendar').hidden, 'Leaving home must close the calendar');
  byId('nav-back').click();
  return { passed: true, checks: 'date component selection, calendar icon, arrows, calendar, history, historical queue/copy, missing days, live updates' };
}

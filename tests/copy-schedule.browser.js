// Run with popup.html and in-memory storage/clipboard fixtures; never writes the real clipboard.
async () => {
  if (!window.previewData || !window.copiedSchedules) throw new Error('In-memory clipboard fixtures required');
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const wait = async read => {
    for (let i = 0; i < 100; i++) { if (read()) return; await new Promise(resolve => setTimeout(resolve, 10)); }
    throw new Error('Copy operation did not finish');
  };
  const cards = [...document.querySelectorAll('.address-card')];
  const selectedDate = document.getElementById('schedule-date').value;
  const address = (await AddressSettings.list()).find(item => DtekSchedule.forDate(item, selectedDate));
  const card = cards.find(item => item.querySelector('strong').textContent === `${address.street}, ${address.house}`);
  const share = card.querySelector('.share-schedule');
  const actions = card.querySelector('.address-actions');
  assert(actions.children[0] === share && actions.children[1].classList.contains('edit-address'), 'Share must be above edit');
  assert(share.querySelector('img').getAttribute('src') === 'images/share.svg', 'Share icon must match');
  assert(actions.children[1].querySelector('img').getAttribute('src') === 'images/edit.svg', 'Edit icon must match');
  assert(!share.disabled, 'A current schedule can be shared');
  share.click();
  assert(!document.getElementById('share-view').hidden, 'Share must open its own page');
  assert(document.getElementById('screen-title').textContent === 'Поділитись графіком', 'Share must have its own heading');
  const editor = document.getElementById('share-text');
  const text = editor.value;
  assert(editor.tagName === 'TEXTAREA' && !editor.readOnly, 'The shared text must be editable');
  assert(text === DtekSchedule.toText(address, DtekSites.get(address.region), DtekSchedule.forDate(address, selectedDate)), 'Preview must use the selected address and day');
  assert(copiedSchedules.length === 0, 'Opening the share page must not copy automatically');
  await wait(() => document.querySelector('#share-qr svg'));
  const svg = document.querySelector('#share-qr svg');
  assert(svg.querySelector('path') && svg.querySelector('rect'), 'QR must include modules and a white background');
  assert(svg.getBoundingClientRect().width <= document.getElementById('share-view').getBoundingClientRect().width, 'QR must fit the popup');
  const qrSnapshot = svg.outerHTML;
  await AddressSettings.saveQueue(address, address.queue || '5.2', { date: selectedDate, lines: [[]] });
  assert(editor.value === text && document.querySelector('#share-qr svg').outerHTML === qrSnapshot,
    'A storage update must not change the text while its QR code is being shared');
  const copy = document.getElementById('copy-shared-schedule');
  assert(copy.querySelector('img').getAttribute('src') === 'images/content-copy.svg', 'Copy button must retain its icon');
  copy.click();
  await wait(() => copiedSchedules.length === 1);
  assert(copiedSchedules[0] === DtekSchedule.toText(address, DtekSites.get(address.region), DtekSchedule.forDate(address, selectedDate)), 'Copy must use this address and schedule date');
  await wait(() => document.getElementById('status').textContent === 'Графік скопійовано.');
  assert(copiedSchedules[0] === text, 'Copied text must match the preview');
  const edited = text + '\nУточнення: перевірте оновлення графіка.';
  editor.value = edited;
  editor.dispatchEvent(new Event('input', { bubbles: true }));
  assert(document.querySelector('#share-qr svg').outerHTML === qrSnapshot, 'Editing must preserve the previous QR during the typing pause');
  await wait(() => document.querySelector('#share-qr svg')?.outerHTML !== qrSnapshot);
  assert(document.querySelector('#share-qr svg').outerHTML !== qrSnapshot, 'Editing must regenerate the QR');
  copy.click();
  await wait(() => copiedSchedules.length === 2);
  assert(copiedSchedules[1] === edited, 'Copy must use the edited text');
  editor.value = '';
  editor.dispatchEvent(new Event('input', { bubbles: true }));
  assert(copy.disabled && !document.querySelector('#share-qr svg'), 'Empty text must disable copying and clear the QR');
  document.getElementById('nav-back').click();
  assert(!document.getElementById('home-view').hidden && document.getElementById('schedule-date').value === selectedDate, 'Back must restore home and the selected day');
  const unavailable = cards.find(item => item.querySelector('.share-schedule').disabled);
  assert(unavailable, 'Missing/stale schedules must not be copied');
  document.getElementById('open-settings').click();
  document.getElementById('auto-close-popups').click();
  await wait(() => !document.getElementById('nav-back').disabled);
  document.getElementById('nav-back').click();
  const refreshedCards = [...document.querySelectorAll('.address-card')];
  assert(refreshedCards.some(item => item.querySelector('.share-schedule').disabled), 'Saving settings must not enable unavailable sharing');
  const write = navigator.clipboard.writeText;
  navigator.clipboard.writeText = async () => { throw new Error('Clipboard unavailable'); };
  refreshedCards.find(item => !item.querySelector('.share-schedule').disabled).querySelector('.share-schedule').click();
  copy.click();
  await wait(() => document.getElementById('status').dataset.error === 'true');
  assert(copiedSchedules.length === 2, 'A failed copy must not report success');
  navigator.clipboard.writeText = write;
  document.getElementById('nav-back').click();
  return { passed: true, checks: 'share page, preview, QR rendering, copy text, action order, icons, unavailable schedules, date preservation, clipboard failure' };
}
